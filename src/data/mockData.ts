/** Plaintext demo passwords exist only in this in-code comparison table. */
export function verifyDemoCredential(username: string, password: string): string | null {
  const normalized = username.trim().toLowerCase();
  const match = DEMO_LOGIN_ACCOUNTS.find(
    (credential) => credential.username === normalized && credential.password === password,
  );
  if (!match) return null;
  return match.username === "admin"
    ? "usr_admin"
    : match.username === "agent"
      ? "usr_agent"
      : "usr_creator";
}

